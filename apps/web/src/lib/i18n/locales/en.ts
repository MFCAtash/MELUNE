/** Same shape as `en`, but with plain `string` leaves so other locales can
 *  hold their own text while still being forced to define every key. */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };
export type Dictionary = Widen<typeof en>;
