#!/usr/bin/env node
/**
 * Validates package-lock.json without touching the network.
 *
 * `npm ci` fails when the lockfile is missing or out of sync with any
 * workspace package.json. This script reproduces the checks that matter so
 * the failure is caught early, with an actionable message:
 *
 *   1. package-lock.json exists and is lockfileVersion >= 2
 *   2. every workspace (root + apps/* + packages/*) has an entry in the lock
 *   3. each entry's dependency maps match its package.json exactly
 *   4. every registry package has an `integrity` hash and an https npmjs URL
 *
 * Exit codes: 0 ok, 1 invalid/out-of-sync, 2 missing (use --allow-missing
 * to downgrade "missing" to a warning and exit 0).
 */
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : ".");
const allowMissing = process.argv.includes("--allow-missing");
const lockPath = join(root, "package-lock.json");

const fail = (msg, code = 1) => {
  console.error(`::error title=Lockfile::${msg}`);
  console.error(`\n✖ ${msg}`);
  console.error("  Fix: run `npm run lockfile:generate` (or the “Generate lockfile” GitHub workflow) and commit package-lock.json.");
  process.exit(code);
};

if (!existsSync(lockPath)) {
  if (allowMissing) {
    console.warn("::warning title=Lockfile::package-lock.json is missing — CI falls back to `npm install`. Commit a lockfile (see docs/lockfile.md).");
    console.warn("⚠ package-lock.json missing (allowed by --allow-missing)");
    process.exit(0);
  }
  fail("package-lock.json is missing. `npm ci` cannot run without it.", 2);
}

let lock;
try {
  lock = JSON.parse(readFileSync(lockPath, "utf8"));
} catch (e) {
  fail(`package-lock.json is not valid JSON: ${e.message}`);
}
if (!lock.lockfileVersion || lock.lockfileVersion < 2 || !lock.packages) {
  fail("package-lock.json must be lockfileVersion 2 or 3 (generated by npm >= 7).");
}

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const rootPkg = readJson(join(root, "package.json"));

// Expand the simple workspace globs used in this repo ("dir" or "dir/*").
const workspaces = [];
for (const pattern of rootPkg.workspaces ?? []) {
  if (pattern.endsWith("/*")) {
    const base = join(root, pattern.slice(0, -2));
    if (!existsSync(base)) continue;
    for (const name of readdirSync(base)) {
      const rel = `${pattern.slice(0, -2)}/${name}`;
      if (statSync(join(root, rel)).isDirectory() && existsSync(join(root, rel, "package.json"))) workspaces.push(rel);
    }
  } else if (existsSync(join(root, pattern, "package.json"))) {
    workspaces.push(pattern);
  }
}

const DEP_FIELDS = ["dependencies", "devDependencies", "optionalDependencies", "peerDependencies"];
const problems = [];

for (const ws of ["", ...workspaces]) {
  const entry = lock.packages[ws];
  const pkg = ws === "" ? rootPkg : readJson(join(root, ws, "package.json"));
  const label = ws === "" ? "(root)" : ws;
  if (!entry) {
    problems.push(`${label}: no entry in package-lock.json`);
    continue;
  }
  for (const field of DEP_FIELDS) {
    const want = pkg[field] ?? {};
    const have = entry[field] ?? {};
    for (const [name, range] of Object.entries(want)) {
      if (have[name] !== range) problems.push(`${label}: ${field}.${name} is "${range}" in package.json but ${have[name] === undefined ? "missing" : `"${have[name]}"`} in lockfile`);
    }
    for (const name of Object.keys(have)) {
      if (!(name in want)) problems.push(`${label}: ${field}.${name} is in lockfile but no longer in package.json`);
    }
  }
}

// Supply-chain hygiene for registry-resolved packages.
for (const [path, meta] of Object.entries(lock.packages)) {
  if (!path.includes("node_modules/") || meta.link || !meta.resolved) continue;
  if (!/^https:\/\/registry\.npmjs\.org\//.test(meta.resolved)) problems.push(`${path}: resolved from non-npmjs host (${meta.resolved})`);
  if (!meta.integrity) problems.push(`${path}: missing integrity hash`);
}

if (problems.length) {
  const shown = problems.slice(0, 25).map((p) => `  - ${p}`).join("\n");
  fail(`package-lock.json is out of sync with package.json files:\n${shown}${problems.length > 25 ? `\n  … and ${problems.length - 25} more` : ""}`);
}

console.log(`✔ package-lock.json OK — lockfileVersion ${lock.lockfileVersion}, ${workspaces.length} workspaces, ${Object.keys(lock.packages).length} entries.`);
